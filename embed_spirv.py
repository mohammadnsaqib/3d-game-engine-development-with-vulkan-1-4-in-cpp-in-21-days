#!/usr/bin/env python3
"""Compile a day's GLSL to SPIR-V and write it into the source as arrays of words.

    python code/embed_spirv.py 01

WHY THE SHADERS GO INTO THE EXECUTABLE. Vulkan does not compile GLSL. It consumes SPIR-V, a
binary format, which means a Vulkan program either ships `.spv` files beside itself or carries
them inside. This book carries them inside, for the same reason Day 21 links the C runtime
statically: the thing a reader hands to somebody else is ONE FILE, and a shader that has gone
missing is a black screen with no error.

WHY NOT COMPILE AT RUN TIME. There are libraries that will (shaderc, and glslang as a library),
and every one of them is a dependency this book does not take. The compiler runs at BUILD time,
which is also when its error messages are useful.

WHAT IT PRODUCES. `src/spirv.h`, one `static const uint32_t` array per shader, named after the
file: `tri.vert` becomes `kTriVert`. SPIR-V is a stream of 32-bit words and its first word is
the magic number 0x07230203, which this checks -- a .spv that does not start with it is not a
.spv, and the message says so here rather than inside vkCreateShaderModule.
"""
from __future__ import annotations

import struct
import subprocess
import sys
from pathlib import Path

CODE = Path(__file__).resolve().parent
BOOK = CODE.parent
SDK = Path("D:/VulkanSDK/1.4.357.0")
GLSLC = SDK / "Bin" / "glslc.exe"

SPIRV_MAGIC = 0x07230203


def camel(name: str) -> str:
    """tri.vert -> kTriVert, lit.frag -> kLitFrag, dust.comp -> kDustComp."""
    stem, _, stage = name.partition(".")
    return "k" + stem[:1].upper() + stem[1:] + stage[:1].upper() + stage[1:]


def main() -> int:
    if len(sys.argv) < 2:
        print("usage: embed_spirv.py NN")
        return 1
    day = sys.argv[1]
    src = BOOK / "code" / "snapshots" / f"day{day}" / "src"
    if not src.is_dir():
        print(f"no such day: {src}")
        return 1
    if not GLSLC.is_file():
        print(f"no glslc at {GLSLC}")
        return 1

    shaders = sorted(p for p in src.iterdir()
                     if p.suffix in (".vert", ".frag", ".comp", ".geom"))
    if not shaders:
        print(f"day{day}: no shaders")
        return 0

    out = [
        "// GENERATED by code/embed_spirv.py. Do not edit by hand.",
        "//",
        "// Each array is the SPIR-V glslc produced from the .vert, .frag or .comp beside this",
        "// file. A word is 32 bits and the first one is always 0x07230203.",
        "#pragma once",
        "#include <cstdint>",
        "",
    ]
    total = 0
    for sh in shaders:
        spv = src / (sh.name + ".spv")
        r = subprocess.run(
            [str(GLSLC), "--target-env=vulkan1.3", "-O", str(sh), "-o", str(spv)],
            capture_output=True, text=True)
        if r.returncode != 0:
            print(f"  {sh.name}: glslc FAILED")
            print(r.stdout or "", r.stderr or "")
            return r.returncode
        data = spv.read_bytes()
        if len(data) < 4 or len(data) % 4:
            print(f"  {sh.name}: {len(data)} bytes is not a whole number of words")
            return 1
        words = struct.unpack(f"<{len(data) // 4}I", data)
        if words[0] != SPIRV_MAGIC:
            print(f"  {sh.name}: first word is 0x{words[0]:08X}, not SPIR-V")
            return 1
        name = camel(sh.name)
        out.append(f"// {sh.name}: {len(words)} words, {len(data)} bytes")
        out.append(f"static const uint32_t {name}[] = {{")
        for i in range(0, len(words), 8):
            row = ", ".join(f"0x{w:08x}" for w in words[i:i + 8])
            out.append(f"    {row},")
        out.append("};")
        out.append("")
        total += len(data)
        spv.unlink()          # the .h is the artefact; the .spv was a step
        print(f"  {sh.name:<16} {len(words):>5} words  ->  {name}")

    (src / "spirv.h").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"day{day}: {len(shaders)} shader(s), {total:,} bytes of SPIR-V in src/spirv.h")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
